export interface StateData {
  code: string;
  name: string;
  slug: string;
  capital: string;
  largestCity: string;
  population: number;
  costOfLivingIndex: number; // 100 = US average
  housingIndex: number;
  groceryIndex: number;
  utilitiesIndex: number;
  transportIndex: number;
  healthIndex: number;
  medianHomePrice: number;
  medianMonthlyRent: number; // 2-bed typical
  medianHouseholdIncome: number;
  stateIncomeTaxType: 'none' | 'flat' | 'graduated';
  stateIncomeTaxMin: number;
  stateIncomeTaxMax: number;
  stateIncomeTaxNote: string;
  avgSalesTax: number; // combined state + local avg
  effectivePropertyTax: number; // % of home value
  gasPriceAvg: number; // $/gallon typical
  sunnyDays: number; // days/year
  avgSummerHigh: number; // °F
  avgWinterLow: number; // °F
  unemploymentRate: number; // %
  jobGrowthRate: number; // % 5-year avg
  transitScore: number; // 0-100
  overallQualityScore: number; // 0-100
  region: 'West' | 'South' | 'Midwest' | 'Northeast' | 'Pacific';
  topPros: string[];
  topCons: string[];
  summary: string;
}

